// Helper functions
export const getProductsByCategory = (category: Product['category']) => {
  return allProducts.filter(p => p.category === category);
};

export const getSmartphones = () => {
  return allProducts.filter(p => p.category === 'smartphone');
};

export const getTablets = () => {
  return allProducts.filter(p => p.category === 'tablet');
};

export const getTelevisions = () => {
  return allProducts.filter(p => p.category === 'television');
};

export const getAccessories = () => {
  return allProducts.filter(p => p.category === 'accessory');
};

export const getKCBEligibleProducts = () => {
  return allProducts.filter(p => p.kcbEligible);
};

export const getSpecialOffers = () => {
  return allProducts.filter(p => p.specialOffer);
};

export const getProductById = (id: string) => {
  return allProducts.find(p => p.id === id);
};

export const getBrands = () => {
  return Array.from(new Set(allProducts.map(p => p.brand))).sort();
};

export const formatPrice = (price: number) => {
  return `KSh ${price.toLocaleString()}`;
};

